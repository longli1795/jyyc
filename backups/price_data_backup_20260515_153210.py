# 辅助函数：根据含税单价计算默认税率
def _get_default_tax_rate(price_with_tax):
    """根据含税单价计算默认税率：正数13%，负数0%"""
    if pd.isna(price_with_tax):
        return 13.0
    price = float(price_with_tax)
    return 13.0 if price > 0 else 0.0

# 辅助函数：根据含税价和税率计算不含税价
def _calculate_price_no_tax(price_with_tax, tax_rate):
    """根据含税价和税率计算不含税价：含税价 / (1 + 税率/100)"""
    if pd.isna(price_with_tax):
        return 0.0
    price = float(price_with_tax)
    if pd.isna(tax_rate) or tax_rate == '':
        tax_rate = 13.0  # 默认税率13%
    else:
        tax_rate = float(tax_rate)
    if tax_rate == 0:
        return price
    return price / (1 + tax_rate / 100)

