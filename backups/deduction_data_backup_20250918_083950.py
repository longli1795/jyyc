def backup_deduction_file():
    """备份减扣数据文件"""
    try:
        import os
        import shutil
        from datetime import datetime
        
        # 创建备份目录
        backup_dir = 'backups'
        if not os.path.exists(backup_dir):
            os.makedirs(backup_dir)
        
        # 生成备份文件名
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        backup_filename = f'deduction_data_{timestamp}.py'
        backup_path = os.path.join(backup_dir, backup_filename)
        
        # 复制当前文件到备份目录
        if os.path.exists('deduction_data.py'):
            shutil.copy2('deduction_data.py', backup_path)
            print(f"✓ 已备份减扣数据文件: {backup_path}")
            return backup_path
        else:
            print("✗ 原文件不存在，无法备份")
            return None
            
    except Exception as e:
        print(f"✗ 备份减扣数据文件失败: {str(e)}")
        return None

