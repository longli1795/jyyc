def get_deep_processing_dataframe():
    """获取深加工数据的DataFrame"""
    import pandas as pd
    if not DEEP_PROCESSING_DATA:
        return pd.DataFrame()
    return pd.DataFrame(DEEP_PROCESSING_DATA)


def _deep_processing_json_path():
    import os
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "deep_processing_coefficients.json")


def save_deep_processing_to_disk():
    """将当前内存中的深加工系数表原子写入 JSON 侧车。"""
    import os
    from data.base_data.base_data_json_persist import atomic_write_json

    global _deep_processing_json_mtime
    try:
        path = _deep_processing_json_path()
        atomic_write_json(path, DEEP_PROCESSING_DATA)
        _deep_processing_json_mtime = os.path.getmtime(path)
        print("[OK] 深加工系数已写入 deep_processing_coefficients.json")
        return True
    except Exception as e:
        print(f"[ERR] 写入深加工系数 JSON 失败: {str(e)}")
        return False


def write_deep_processing_data_to_file():
    """将深加工数据写入 JSON 侧车。"""
    return save_deep_processing_to_disk()


def backup_deep_processing_file():
    """备份深加工 JSON 侧车（若不存在则跳过）。"""
    import os
    from data.base_data.base_data_json_persist import backup_json_sidecar

    path = _deep_processing_json_path()
    if not os.path.exists(path):
        return None
    try:
        dest = backup_json_sidecar(path, "deep_processing_coefficients")
        if dest:
            print(f"[OK] 已备份深加工系数: {dest}")
        return dest
    except Exception as e:
        print(f"[ERR] 备份深加工系数失败: {str(e)}")
        return None


def apply_deep_processing_snapshot(data: list):
    """用快照完全替换内存中的深加工系数表（用于发布同步等）。"""
    if not isinstance(data, list):
        raise TypeError("deep processing snapshot must be a list")
    DEEP_PROCESSING_DATA[:] = data
    return save_deep_processing_to_disk()


_deep_processing_json_mtime = 0.0


def _load_deep_processing_json_if_present():
    import json
    import os

    global _deep_processing_json_mtime
    path = _deep_processing_json_path()
    if not os.path.exists(path):
        return
    try:
        with open(path, encoding="utf-8") as f:
            loaded = json.load(f)
        if not isinstance(loaded, list):
            print("[WARN] deep_processing_coefficients.json 格式无效，已跳过加载")
            return
        DEEP_PROCESSING_DATA[:] = loaded
        _deep_processing_json_mtime = os.path.getmtime(path)
        print(f"[OK] 已从 JSON 侧车加载深加工系数: {path}")
    except Exception as e:
        print(f"[WARN] 加载 deep_processing_coefficients.json 失败，使用内置默认: {e}")


def reload_deep_processing_json_if_stale():
    """若 JSON 侧车已更新，则重新加载。"""
    import os

    global _deep_processing_json_mtime
    path = _deep_processing_json_path()
    if not os.path.exists(path):
        return
    m = os.path.getmtime(path)
    if m != _deep_processing_json_mtime:
        _load_deep_processing_json_if_present()


_load_deep_processing_json_if_present()
